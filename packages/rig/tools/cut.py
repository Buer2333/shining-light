"""Cut a front-view character image into rig parts + a rig spec v1 (rig.json).

usage: cut.py <config.json> <out_dir> [--debug out.jpg] [--no-stamp]

The character config holds everything character-specific (see docs/spec.md):
  source            image path, relative to the config file
  cut               image processing: background (flood fill, or the source's alpha), erosion, part polygons, joints, ball joints,
                    protect regions (e.g. a chest logo), flat-fill sample points, mesh polygons, caps
  rig               the rest of the spec (channels, joint parents, groups, variants, mesh limbs, face) copied as is
Polygons and joints are in "display" coordinates (the scale you measured them at); display_width maps them to
source pixels (K = image width / display_width). Right-side parts/joints can be generated by mirroring.
The library itself holds no character constants: every step below is driven by the config and can be switched off.
"""
import argparse
import hashlib
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from provenance import stamp_or_exit  # noqa: E402


def foreground(im, bg, raw=None):
    """Foreground mask. method "alpha": the source's own alpha > alpha_gt (transparent PNG art).
    Default ("flood"): flood fill of the background from seed points (threshold protects dark outlines)."""
    method = bg.get("method", "flood")
    if method == "alpha":
        if raw is None or "A" not in raw.getbands():
            raise SystemExit("background method alpha needs a source image with an alpha channel")
        return raw.getchannel("A").point(lambda v: 255 if v > bg.get("alpha_gt", 127) else 0)
    if method != "flood":
        raise SystemExit(f"unknown background method {method}")
    W, H = im.size
    mask = im.copy()
    for sx, sy in bg["seeds"]:
        x = {"W-1": W - 1, "W/2": W // 2}.get(sx, sx) if isinstance(sx, str) else sx
        y = {"H-1": H - 1}.get(sy, sy) if isinstance(sy, str) else sy
        ImageDraw.floodfill(mask, (x, y), (255, 0, 255), thresh=bg["thresh"])
    fg = Image.new("L", im.size, 0)
    px, a = mask.load(), fg.load()
    for y in range(H):
        for x in range(W):
            if px[x, y] != (255, 0, 255):
                a[x, y] = 255
    return fg


def red_bbox(im, K, reg):
    """Bounding box (source px, padded) of strongly red pixels inside a window; None when there are none."""
    red = Image.eval(im.split()[0], lambda v: 255 if v > reg["r_gt"] else 0)
    red = Image.composite(red, Image.new("L", im.size, 0), Image.eval(im.split()[1], lambda v: 255 if v < reg["g_lt"] else 0))
    wx0, wy0, wx1, wy1 = reg["window"]
    lb = red.crop((int(wx0 * K), int(wy0 * K), int(wx1 * K), int(wy1 * K))).getbbox()
    if lb is None:
        return None
    p = reg["pad"]
    return [int(wx0 * K) + lb[0] - p, int(wy0 * K) + lb[1] - p, int(wx0 * K) + lb[2] + p, int(wy0 * K) + lb[3] + p]


def build_spec(cfg, size, scale, joints_px, bbox, caps, gen, source_sha256):
    """Assemble rig spec v1 from measured geometry + the config's rig template (shared with spec_migrate)."""
    rig = cfg["rig"]
    parent = rig.get("joint_parents", {})
    # only joints generated by mirror_joints are mirrors; a right side measured on its own (asymmetric art) is not
    mirror_of = {p + "R": p + "L" for p in cfg["cut"].get("mirror_joints", []) if p + "R" in joints_px and p + "L" in joints_px}
    spec = {
        "spec_version": 1,
        "character_id": cfg["character_id"],
        "rig_type": rig["rig_type"],
        "coord_space": {"size": list(size), "y_down": True, "deg_cw": True},
        "scale": scale,
        "joints": {k: {"pivot": v, "parent": parent.get(k), **({"mirror_of": mirror_of[k]} if k in mirror_of else {}),
                       **rig.get("joint_flags", {}).get(k, {})} for k, v in joints_px.items()},  # flags: unscale / level
        "channels": rig["channels"],
        "parts": [{"id": k, "joint": rig["part_joints"].get(k), "bbox": b, "asset": f"{k}.png"} for k, b in bbox.items()],
        "caps": caps,
        "groups": rig["groups"],
        "variants": rig["variants"],
        "source_sha256": source_sha256,
        "generator": gen,
    }
    if "mesh" in rig:
        spec["mesh"] = rig["mesh"]
    for k in ("face", "rest_keypoints", "keypoint_map"):
        if k in rig:
            spec[k] = rig[k]
    return spec


def cut(cfg, cfg_dir, out, stamp=True, debug=None):
    gen = stamp_or_exit(stamp)
    c = cfg["cut"]
    src = os.path.join(cfg_dir, cfg["source"])
    raw = Image.open(src)
    im = raw.convert("RGB")
    W, H = im.size
    DW = c["display_width"]
    K = W / DW
    os.makedirs(out, exist_ok=True)
    fg = foreground(im, c["background"], raw)
    if c.get("erode_px", 0):
        fg = fg.filter(ImageFilter.MinFilter(2 * c["erode_px"] + 1))  # pull the alpha edge onto the dark outline
    rgba = im.copy().convert("RGBA")
    rgba.putalpha(fg)
    M = lambda pts: [(x * K, y * K) for x, y in pts]
    mir = lambda pts: [(DW - x, y) for x, y in pts]

    P = {k: v for k, v in c["polygons"].items()}
    for right, left in c.get("mirror_parts", []):
        P[right] = mir(P[left])
    J = {k: tuple(v) for k, v in c["joints"].items()}
    for prefix in c.get("mirror_joints", []):
        J[prefix + "R"] = (DW - J[prefix + "L"][0], J[prefix + "L"][1])
    joints_px = {k: [round(v[0] * K, 1), round(v[1] * K, 1)] for k, v in J.items()}
    bbox = {}

    ZERO = Image.new("L", im.size, 0)
    protect = ZERO.copy()
    for reg in c.get("protect_regions", []):
        if not reg.get("enabled", True):
            continue
        if reg["method"] != "red_bbox":
            raise SystemExit(f"unknown protect_regions method {reg['method']}")
        b = red_bbox(im, K, reg)
        if b is not None:
            ImageDraw.Draw(protect).rectangle(b, fill=255)
    dk = c.get("dark", {"lum_lt": 200, "grow": 3})
    dark = Image.eval(im.convert("L"), lambda v: 255 if v < dk["lum_lt"] else 0).filter(ImageFilter.MaxFilter(dk["grow"]))

    def save(name, part, m):
        al = Image.composite(fg, ZERO, m)
        part.putalpha(al)
        bb = al.getbbox()
        part.crop(bb).save(f"{out}/{name}.png")
        bbox[name] = list(bb)

    balls = c.get("ball_joints", {})
    for name, poly in P.items():
        m = Image.new("L", im.size, 0)
        ImageDraw.Draw(m).polygon(M(poly), fill=255)
        part = rgba.copy()
        if name in balls:
            # Ball joint: the sleeve's inner end is cut to a half disc around the pivot, and the disc itself becomes a
            # cap part that never rotates. The cap keeps the original shoulder line (top band), the rest is flat-filled.
            bj = balls[name]
            jx, jy = J[bj["joint"]]
            r = bj["radius"]
            disc = ZERO.copy()
            ImageDraw.Draw(disc).ellipse([(jx - r) * K, (jy - r) * K, (jx + r) * K, (jy + r) * K], fill=255)
            g = bj.get("paint_margin", 2)
            disc2 = ZERO.copy()
            ImageDraw.Draw(disc2).ellipse([(jx - r - g) * K, (jy - r - g) * K, (jx + r + g) * K, (jy + r + g) * K], fill=255)
            ff = bj.get("flat_fill", {"enabled": False})
            if ff.get("enabled"):
                flat = Image.new("RGBA", im.size, im.getpixel((int((jx + ff["dx"]) * K), int(jy * K))) + (255,))
                top = ZERO.copy()
                ImageDraw.Draw(top).rectangle([0, 0, W, (jy - r + bj.get("keep_top_band", 14)) * K], fill=255)
                keep = Image.composite(dark, ZERO, top)
                cap = Image.composite(rgba.copy(), flat, keep)
            else:
                cap = rgba.copy()
            save(bj["cap_part"], cap, Image.composite(ZERO, disc, protect))
            half = ZERO.copy()
            ImageDraw.Draw(half).rectangle([0, 0, jx * K, H] if bj["outward"] == "left" else [jx * K, 0, W, H], fill=255)
            m = Image.composite(m, ZERO, Image.composite(half, disc, Image.eval(disc, lambda v: 255 - v)))
            if ff.get("enabled"):
                part = Image.composite(flat, part, Image.composite(dark, ZERO, disc2))
        save(name, part, m)

    PM = {k: v for k, v in c.get("mesh_polygons", {}).items()}
    for right, left in c.get("mirror_mesh", []):
        PM[right] = mir(PM[left])
    for name, poly in PM.items():
        m = ZERO.copy()
        ImageDraw.Draw(m).polygon(M(poly), fill=255)
        save(name, rgba.copy(), m)

    def col(x, y):
        return im.getpixel((int(x * K), int(y * K)))

    caps = {k: {"at": joints_px[v["joint"]], "r": v["r"] * K, "color": "#%02x%02x%02x" % col(*v["sample"])} for k, v in c.get("caps", {}).items()}

    if "scale" in c:
        scale = dict(c["scale"])
    else:
        fb = fg.getbbox()
        scale = {"body_h_px": fb[3] - fb[1], "ground_y": fb[3], "source": "measured: foreground alpha bbox"}
    spec = build_spec(cfg, [W, H], scale, joints_px, bbox, caps, gen, hashlib.sha256(open(src, "rb").read()).hexdigest())
    json.dump(spec, open(f"{out}/rig.json", "w"), indent=1)

    if debug:
        dbg = rgba.copy()
        d = ImageDraw.Draw(dbg)
        cols = ["#e6194b", "#3cb44b", "#4363d8", "#f58231", "#911eb4", "#46f0f0", "#f032e6", "#bcf60c", "#008080", "#9a6324"]
        for i, (n, poly) in enumerate(P.items()):
            d.line(M(poly + [poly[0]]), fill=cols[i % 10], width=6)
        for n, (x, y) in J.items():
            d.ellipse([x * K - 14, y * K - 14, x * K + 14, y * K + 14], fill="red")
        bgw = Image.new("RGBA", dbg.size, (235, 235, 235, 255))
        bgw.alpha_composite(dbg)
        bgw.convert("RGB").resize((1024, int(1024 * H / W))).save(debug)
    return spec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("config")
    ap.add_argument("out")
    ap.add_argument("--debug")
    ap.add_argument("--no-stamp", action="store_true", help="tests only: artifacts are marked unstamped")
    a = ap.parse_args()
    cfg = json.load(open(a.config))
    spec = cut(cfg, os.path.dirname(os.path.abspath(a.config)), a.out, stamp=not a.no_stamp, debug=a.debug)
    print(f"{len(spec['parts'])} parts, {len(spec['joints'])} joints -> {a.out}/rig.json ({spec['generator']})")


if __name__ == "__main__":
    main()
